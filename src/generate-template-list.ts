// generate-template-list.ts
//
// Fetches every exercise template in your Hevy account (built-in + custom) and writes
//   data/HEVY_EXERCISES.ts     ALL_CAPS key → template id, for the exercise map
//   data/hevy-templates.json   full metadata (type, equipment, muscles, is_custom, thumbnail)
import { DATA, HEVY_API_KEY, HEVY_API_BASE } from './config.ts';

if (!HEVY_API_KEY) {
  console.error("Set HEVY_API_KEY in .env");
  Deno.exit(1);
}

const toKey = (title: string) => {
  const key = title.toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');
  return /^[0-9]/.test(key) ? `_${key}` : key;
};

const templates: { id: string; title: string }[] = [];
let page = 1, pageCount = 1;

while (page <= pageCount) {
  const res = await fetch(`${HEVY_API_BASE}/exercise_templates?page=${page}&pageSize=100`, {
    headers: { 'api-key': HEVY_API_KEY }
  });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
  const data = await res.json();
  pageCount = data.page_count ?? 1;
  templates.push(...data.exercise_templates);
  page++;
}

const lines = templates.map((e) => `  ${toKey(e.title)}: "${e.id}",`).join('\n');
await Deno.writeTextFile(
  `${DATA}/HEVY_EXERCISES.ts`,
  `// HEVY_EXERCISES.ts\n// Generated by generate-template-list.ts — do not edit manually\n\nexport const HEVY_EXERCISES: Record<string, string> = {\n${lines}\n};\n`
);
await Deno.writeTextFile(`${DATA}/hevy-templates.json`, JSON.stringify(templates, null, 1) + '\n');
console.log(`Generated ${DATA}/HEVY_EXERCISES.ts and ${DATA}/hevy-templates.json with ${templates.length} exercises.`);
